export type CompositionPlan = {
  path: string;
  opening: string;
  ending: string;
  allowOrdinalMarkers: boolean;
  allowConclusionFormula: boolean;
  budget: { introduction: number; body: number[]; counterargument: number; conclusion: number };
};

export function createCompositionPlan(
  params: Parameters,
  variation = randomInt(0, 0x7fffffff),
): CompositionPlan {
  const genre = genres[params.essayType];
  const seed = Math.abs(Math.trunc(variation));
  const introduction = Math.round(params.targetWordCount * 0.16);
  const conclusion = Math.round(params.targetWordCount * 0.16);
  const counterargument = params.includeCounterargument
    ? Math.round(params.targetWordCount * 0.13)
    : 0;
  const remaining = params.targetWordCount - introduction - conclusion - counterargument;
  return {
    path: genre.paths[seed % genre.paths.length],
    opening: genre.openings[Math.floor(seed / 3) % genre.openings.length],
    ending: genre.endings[Math.floor(seed / 9) % genre.endings.length],
    allowOrdinalMarkers:
      ['Академиялық', 'Дәлелдеу', 'Пікірталастық'].includes(params.essayType) &&
      ['Ғылыми', 'Академиялық', 'Ресми-іскери'].includes(params.style) &&
      seed % 3 === 0,
    allowConclusionFormula:
      ['Ғылыми', 'Академиялық', 'Ресми-іскери'].includes(params.style) && seed % 3 === 0,
    budget: {
      introduction,
      conclusion,
      counterargument,
      body: Array.from(
        { length: params.argumentsCount },
        (_, i) =>
          Math.floor(remaining / params.argumentsCount) +
          Number(i < remaining % params.argumentsCount),
      ),
    },
  };
}

